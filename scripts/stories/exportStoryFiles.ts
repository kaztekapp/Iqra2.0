/**
 * Writes the prophet stories the app reads: one data file per prophet in
 * assets/stories/, from the source files in src/data/arabic/prophets/stories
 * (the master copy, which the voice recorder and the tests read).
 *
 * Why files and not code: the stories were 5 MB of the app's JavaScript, and
 * every over-the-air update re-sends all of the JavaScript to every phone. A
 * data file ships inside the store build and is sent again only when that
 * story changes.
 *
 * Run after any change to a story:  npx tsx scripts/stories/exportStoryFiles.ts
 * __tests__/storyFiles.test.ts fails if the two ever differ.
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getProphetStorySource, getProphetsWithStorySource } from '../../src/data/arabic/prophets/source';

const OUT = join(__dirname, '..', '..', 'assets', 'stories');

// Android resource names allow only a-z, 0-9 and _.
export const storyFileName = (id: string) => `${id.replace(/[^a-z0-9]/g, '_')}.qjson`;

if (require.main === module) {
  const ids = getProphetsWithStorySource();
  mkdirSync(OUT, { recursive: true });
  // A story removed from the source must not linger as a file.
  for (const f of readdirSync(OUT)) if (f.endsWith('.qjson')) rmSync(join(OUT, f));
  let bytes = 0;
  for (const id of ids) {
    const text = JSON.stringify(getProphetStorySource(id));
    bytes += Buffer.byteLength(text);
    writeFileSync(join(OUT, storyFileName(id)), text);
  }
  writeFileSync(
    join(OUT, 'index.ts'),
    `// Generated by scripts/stories/exportStoryFiles.ts - do not edit.\n` +
      `// Each prophet's story as a data file (an asset), not JavaScript.\n` +
      `export const STORY_FILES: Record<string, number> = {\n${ids.map((id) => `  ${JSON.stringify(id)}: require('./${storyFileName(id)}'),`).join('\n')}\n};\n`
  );
  console.log(`wrote ${ids.length} story files, ${(bytes / 1e6).toFixed(1)} MB`);
}
