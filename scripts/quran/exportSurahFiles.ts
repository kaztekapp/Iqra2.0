/**
 * Writes the Quran the app reads: one data file per surah in assets/quran/,
 * from the source files in src/data/arabic/quran/surahs (which stay the
 * master copy: the voice recorder and the tests read them).
 *
 * Why files and not code: the source files were 20 MB of the app's 28 MB of
 * JavaScript, and every over-the-air update re-sends all of the JavaScript to
 * every phone. A data file is downloaded once (or ships inside the store
 * build) and is sent again only if it changes.
 *
 * Run after any change to the source files:  npx tsx scripts/quran/exportSurahFiles.ts
 * __tests__/quranFiles.test.ts fails if the two ever differ.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { QURAN_BY_JUZ } from '../../src/data/arabic/quran/surahs/allSurahs';
import { SURAH_ID_TO_NUMBER } from '../../src/data/arabic/quran/surahIds';
import type { Ayah } from '../../src/types/quran';

const OUT = join(__dirname, '..', '..', 'assets', 'quran');

/** Each surah's verses, from the first juz it appears in (where its file lives). */
export function surahsFromSource(): Map<number, Ayah[]> {
  const out = new Map<number, Ayah[]>();
  for (let juz = 1; juz <= 30; juz++) {
    for (const ayahs of Object.values(QURAN_BY_JUZ[juz] ?? {}) as Ayah[][]) {
      const n = ayahs[0] && SURAH_ID_TO_NUMBER[ayahs[0].surahId];
      if (n && !out.has(n)) out.set(n, ayahs);
    }
  }
  return out;
}

export const fileName = (n: number) => `${String(n).padStart(3, '0')}.qjson`;

if (require.main === module) {
  const surahs = surahsFromSource();
  if (surahs.size !== 114) throw new Error(`expected 114 surahs, found ${surahs.size}`);
  mkdirSync(OUT, { recursive: true });
  let bytes = 0;
  for (const [n, ayahs] of surahs) {
    const text = JSON.stringify(ayahs);
    bytes += Buffer.byteLength(text);
    writeFileSync(join(OUT, fileName(n)), text);
  }
  const lines = [...surahs.keys()].sort((a, b) => a - b).map((n) => `  ${n}: require('./${fileName(n)}'),`);
  writeFileSync(
    join(OUT, 'index.ts'),
    `// Generated by scripts/quran/exportSurahFiles.ts - do not edit.\n` +
      `// Each surah's verses as a data file (an asset), not JavaScript.\n` +
      `export const SURAH_FILES: Record<number, number> = {\n${lines.join('\n')}\n};\n`
  );
  console.log(`wrote 114 surah files, ${(bytes / 1e6).toFixed(1)} MB`);
}
